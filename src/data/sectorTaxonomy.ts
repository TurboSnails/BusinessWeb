/** ADR 的 GICS 一级：batch 已是 GICS 一级；SOFI 的 batch 为子行业「金融科技」，由 SECTOR_FIXES 归金融 */
const adrGics = (c: Company): string => SECTOR_FIXES[`adr:${c.code}`] ?? c.batch

export function applySectorTaxonomy<T extends Company>(c: T): T {
  const key = `${c.market}:${c.code}`
  if (c.market === 'cn') {
    const csi = CN_CSI_LEVEL1[c.code]
    const theme = c.theme ?? (CN_THEMES.has(c.sector) ? c.sector : undefined)
    const sector = csi ?? SECTOR_FIXES[key] ?? c.sector
    if (sector === c.sector && theme === c.theme) return c
    return { ...c, sector, ...(theme ? { theme } : {}) }
  }
  if (c.market === 'adr') {
    if (!ADR_REGIONS.has(c.sector)) {
      const fixed = SECTOR_FIXES[key]
      return fixed && fixed !== c.sector ? { ...c, sector: fixed } : c
    }
    return { ...c, region: c.region ?? c.sector, sector: adrGics(c) }
  }
  const fixed = SECTOR_FIXES[key]
  return fixed && fixed !== c.sector ? { ...c, sector: fixed } : c
}
