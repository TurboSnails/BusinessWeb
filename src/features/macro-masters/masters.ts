export type IndicatorCoverage = {
  exact: number
  proxy: number
  empty: number
  method: number
  measurable: number
}

export function indicatorCoverage(master: Master): IndicatorCoverage {
  const coverage: IndicatorCoverage = { exact: 0, proxy: 0, empty: 0, method: 0, measurable: 0 }
  for (const indicator of master.indicators) {
    if (indicator.kind === 'method') coverage.method += 1
    else if (indicator.readings?.length) coverage.exact += 1
    else if (indicator.proxyReadings?.length) coverage.proxy += 1
    else coverage.empty += 1
  }
  coverage.measurable = coverage.exact + coverage.proxy + coverage.empty
  return coverage
}

export function masterBySlug(slug: string | undefined): Master | undefined {
  return MASTERS.find(master => master.slug === slug)
}
