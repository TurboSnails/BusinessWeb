function timeline(): RadarFile['backtest']['timeline'] {
  const radar: Array<TierId | null> = [
    'offense', 'lean-offense', 'neutral', 'lean-defense', 'defense',
    'lean-defense', 'neutral', 'lean-offense', 'offense', 'lean-offense',
    'neutral', 'lean-offense',
  ]
  const dimScores = [0, -0.5, -0.67, 0, 1]
  return radar.map((tier, i) => {
    const month = String((i % 12) + 1).padStart(2, '0')
    const year = 2025 + Math.floor(i / 12)
    const score = -0.2 + Math.sin(i / 4) * 0.15
    return {
      d: `${year}-${month}`,
      radar: tier,
      spx: 4800 + i * 20,
      score,
      dims: dimScores.map((v, di) => v + Math.sin((i + di) / 5) * 0.1),
    }
  })
}

function curves(): RadarFile['backtest']['curves'] {
  // 1973-01 起约 646 个月量级太重；给够「近 10 年」(120) + 更早若干月，方便回测区图渲染
  const startYear = 1995
  const months = (2026 - startYear) * 12 + 10
  return Array.from({ length: months }, (_, i) => {
    const year = startYear + Math.floor(i / 12)
    const month = String((i % 12) + 1).padStart(2, '0')
    const t = 1 + i * 0.004
    return {
      d: `${year}-${month}`,
      radar: Number((t * 1.02).toFixed(4)),
      trend: Number((t * 1.01).toFixed(4)),
      buyhold: Number(t.toFixed(4)),
      static70: Number((t * 0.99).toFixed(4)),
    }
  })
}

