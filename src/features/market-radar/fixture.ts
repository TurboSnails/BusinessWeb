function history(n = 36, start = 0.4): [string, number][] {
  return Array.from({ length: n }, (_, i) => {
    const month = String((i % 12) + 1).padStart(2, '0')
    const year = 2023 + Math.floor(i / 12)
    return [`${year}-${month}-28`, start + Math.sin(i / 3) * 0.15] as [string, number]
  })
}

function emptyCounts(): RadarFile['current']['counts'] {
  return {
    total: 0,
    scored: 0,
    core: 0,
    heat: { hot: 0, warm: 0, neutral: 0, cool: 0, cold: 0, na: 0 },
    status: { fresh: 0, stale: 0, discontinued: 0, sparse: 0 },
  }
}

function recount(indicators: RadarIndicator[]): RadarFile['current']['counts'] {
  const counts = emptyCounts()
  counts.total = indicators.length
  for (const item of indicators) {
    if (item.inScore) counts.scored += 1
    if (item.core) counts.core += 1
    counts.heat[item.heat] += 1
    counts.status[item.status] += 1
  }
  return counts
}

function forwardStats(months: number, fwd12: number | null = 0.08): RadarForwardStats {
  if (months === 0) return { months: 0, fwd12: null, neg12: null, maxDd12: null }
  return { months, fwd12, neg12: 0.25, maxDd12: -0.12 }
}

